def esc(s):
    return s.replace("\\", "\\\\").replace("'", "''")

def tuple_sql(idx, r):
    name, pid, cid, level, desc, addr, otime, price, rating, views = r
    return (f"('{esc(name)}',{pid},{cid},'{level}','/img/scenic/a{idx}.jpg','{esc(desc)}',"
            f"'{esc(addr)}','{esc(otime)}',{price:.2f},{rating},{views},1)")

